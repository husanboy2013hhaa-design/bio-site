def _database_from_url(url: str) -> dict:
    """Parse postgres://user:pass@host:port/db?... into a Django DATABASES entry.

    Uses DIRECT_URL (session mode) by default — Django keeps long-lived
    connections, which pgbouncer transaction mode (port 6543) breaks.
    """
    from urllib.parse import parse_qs, unquote, urlparse

    u = urlparse(url)
    options = {"sslmode": os.getenv("DB_SSLMODE", "require")}
    if u.port == 6543:
        # pgbouncer transaction mode rejects prepared statements (psycopg3)
        options["prepare_threshold"] = None
    options.update(
        {
            k: v[0]
            for k, v in parse_qs(u.query).items()
            if k in ("sslmode", "connect_timeout", "application_name")
        }
    )
    return {
        "ENGINE": "django.db.backends.postgresql",
        "NAME": (u.path or "/postgres").lstrip("/").split("?")[0] or "postgres",
        "USER": unquote(u.username or ""),
        "PASSWORD": unquote(u.password or ""),
        "HOST": u.hostname or "localhost",
        "PORT": str(u.port or 5432),
        # Serverless (Vercel): DB_CONN_MAX_AGE=0 closes after each request so
        # warm lambdas don't exhaust Supabase's session pool (15 clients).
        "CONN_MAX_AGE": int(os.getenv("DB_CONN_MAX_AGE", "60")),
        "OPTIONS": options,
    }


