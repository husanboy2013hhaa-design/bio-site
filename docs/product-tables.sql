BEGIN;

-- -----------------------------------------------------------------------------
-- 1. Users — custom model: email = login key, username = public handle seed
-- -----------------------------------------------------------------------------
CREATE TABLE accounts_user (
    id              bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    password        varchar(128) NOT NULL,          -- PBKDF2 hash
    last_login      timestamptz NULL,
    is_superuser    boolean NOT NULL,
    first_name      varchar(150) NOT NULL DEFAULT '',
    last_name       varchar(150) NOT NULL DEFAULT '',
    is_staff        boolean NOT NULL,
    is_active       boolean NOT NULL,
    date_joined     timestamptz NOT NULL,
    email           varchar(254) NOT NULL UNIQUE,   -- login identifier
    username        varchar(30)  NOT NULL UNIQUE    -- seed for the public slug
);

-- -----------------------------------------------------------------------------
-- 2. Profiles — one per user; slug is the public URL handle /<slug>
-- -----------------------------------------------------------------------------
CREATE TABLE profiles_profile (
    id           bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    slug         varchar(40)  NOT NULL UNIQUE,      -- reserved words blocked in app code
    display_name varchar(60)  NOT NULL DEFAULT '',
    bio          varchar(160) NOT NULL DEFAULT '',
    avatar       varchar(100) NULL,                 -- media path (avatars/…)
    is_public    boolean NOT NULL,
    clicks_total bigint NOT NULL,                   -- denormalised counters
    views_total  bigint NOT NULL,
    created_at   timestamptz NOT NULL,
    updated_at   timestamptz NOT NULL,
    user_id      bigint NOT NULL UNIQUE REFERENCES accounts_user (id) ON DELETE CASCADE
);
CREATE INDEX profiles_profile_slug_552b86bf_like ON profiles_profile (slug varchar_pattern_ops);

-- -----------------------------------------------------------------------------
-- 3. Themes — 1:1 with profile; hex colors validated in app code
-- -----------------------------------------------------------------------------
CREATE TABLE profiles_theme (
    id               bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    background       varchar(7) NOT NULL,           -- #0f172a
    text_color       varchar(7) NOT NULL,
    button_color     varchar(7) NOT NULL,
    button_text_color varchar(7) NOT NULL,
    button_style     varchar(10) NOT NULL,          -- square | rounded | pill
    font             varchar(10) NOT NULL,          -- Inter | system | serif | mono
    background_image varchar(100) NULL,
    updated_at       timestamptz NOT NULL,
    profile_id       bigint NOT NULL UNIQUE REFERENCES profiles_profile (id) ON DELETE CASCADE
);

-- -----------------------------------------------------------------------------
-- 4. Links — ordered, toggleable outbound links per profile
-- -----------------------------------------------------------------------------
CREATE TABLE links_link (
    id          bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    title       varchar(80)  NOT NULL,
    url         varchar(500) NOT NULL,              -- http(s) only, validated in app
    description varchar(160) NOT NULL DEFAULT '',
    icon        varchar(40)  NOT NULL DEFAULT '',
    position    integer      NOT NULL DEFAULT 0 CHECK (position >= 0),
    is_active   boolean      NOT NULL,
    clicks      bigint       NOT NULL DEFAULT 0,    -- denormalised counter
    created_at  timestamptz NOT NULL,
    updated_at  timestamptz NOT NULL,
    profile_id  bigint NOT NULL REFERENCES profiles_profile (id) ON DELETE CASCADE,
    CONSTRAINT unique_link_position_per_profile UNIQUE (profile_id, position)
);
CREATE INDEX links_link_profile_48fab6_idx ON links_link (profile_id, is_active, position);

-- -----------------------------------------------------------------------------
-- 5. Click events — raw analytics stream (privacy: salted IP hash, no raw IPs)
-- -----------------------------------------------------------------------------
CREATE TABLE links_clickevent (
    id         bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    created_at timestamptz NOT NULL,
    referrer   varchar(255) NOT NULL DEFAULT '',
    user_agent varchar(255) NOT NULL DEFAULT '',
    ip_hash    varchar(64)  NOT NULL DEFAULT '',    -- sha256(salt:ip)
    country    varchar(2)   NOT NULL DEFAULT '',    -- optional GeoIP
    link_id    bigint NOT NULL REFERENCES links_link (id) ON DELETE CASCADE
);
CREATE INDEX click_link_created_idx           ON links_clickevent (link_id, created_at);
CREATE INDEX links_clickevent_created_at_idx  ON links_clickevent (created_at);

-- -----------------------------------------------------------------------------
-- 6. Daily stats — materialised rollup for fast dashboards
--    (link_id NULL = whole-profile rollup)
-- -----------------------------------------------------------------------------
CREATE TABLE analytics_dailystat (
    id         bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    date       date NOT NULL,
    clicks     integer NOT NULL DEFAULT 0 CHECK (clicks >= 0),
    views      integer NOT NULL DEFAULT 0 CHECK (views >= 0),
    link_id    bigint NULL REFERENCES links_link (id) ON DELETE CASCADE,
    profile_id bigint NOT NULL REFERENCES profiles_profile (id) ON DELETE CASCADE,
    CONSTRAINT unique_daily_stat UNIQUE (profile_id, link_id, date)
);
CREATE INDEX analytics_dailystat_profile_date_idx ON analytics_dailystat (profile_id, date);

COMMIT;
